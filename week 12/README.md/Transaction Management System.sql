Week 12 – Transaction Management System

Project Overview

This project focuses on implementing transaction management in an E-Commerce Database using MySQL.
It demonstrates order placement, payment processing, stock updates, 
and transaction control using COMMIT and ROLLBACK.

##  Transaction Reports

### Report 1 – Order Transaction Report
Displays order ID, customer name, order amount, payment status, and order status. It helps monitor completed and pending orders.

